#include <atomic>
#include <thread>
#include <condition_variable>
#include <mutex>
#include <string>
#include <fstream>
#include "SaveManager.h"
#include "Common.h"
#include "Config.h"
#include "PlayerTracker.h"

std::atomic<bool> g_RunSaveManagerThread(false);
std::mutex g_SaveManagerMutex;
std::condition_variable g_SaveManagerCV;
std::atomic<bool> g_EnableSaving(false);

const std::string g_SavePath = ".\\CoreManagement.dat";

void AsyncSaveManagerWorker() {
    while (g_RunSaveManagerThread) {
        std::unique_lock<std::mutex> lock(g_SaveManagerMutex);

		// Save every 60 seconds or when the thread is signaled to shut down
        g_SaveManagerCV.wait_for(lock, std::chrono::milliseconds(60000), [&] {
            return !g_RunSaveManagerThread.load(std::memory_order_acquire);
            });

        // If we were woken up to shut down and the queue is completely empty, 
        // break instantly to skip the slow disk I/O operations entirely.
        if (!g_RunSaveManagerThread.load(std::memory_order_acquire)) {
            break;
        }

        if (g_EnableSaving.load(std::memory_order_acquire)) {
            PlayerSaveState playerSaveState = g_playerTracker.GetPlayerSaveState();
            std::ofstream saveFile(g_SavePath, std::ios::out | std::ios::trunc);
            if (saveFile.is_open()) {
                saveFile << "CoreManagement Save File\n"
                    << "========================================================================================================\n"
                    << "Version: " << VERSION << "\n"
                    << "This file is automatically generated by the CoreManagement mod. Do not edit manually.\n"
                    << "If you wish to reset the mod's state, delete this file and restart the game.\n"
                    << "This file is used to persist the mod's state across game sessions.\n"
                    << "If you encounter issues, please report them to the mod developer.\n"
                    << "For more information, visit the mod's official documentation or support channels.\n"
                    << "========================================================================================================\n\n"
                    << "PostMissionDecayHoursRemaining=" << g_State.PostMissionDecayHoursRemaining << "\n";

                if (playerSaveState.IsValid()) {
                    saveFile << "LastSleptHours=" << playerSaveState.LastSleptHours << "\n"
                        << "LastSleptAtNight=" << (playerSaveState.LastSleptAtNight ? "1" : "0") << "\n";
                }

                saveFile.flush();
                saveFile.close();

                LOG_DEV("Saved player state to {}: LastSleptHours={}, LastSleptAtNight={}, PostMissionDecayHoursRemaining={}", g_SavePath,
                    playerSaveState.LastSleptHours, playerSaveState.LastSleptAtNight, g_State.PostMissionDecayHoursRemaining);
            }
        }
    }
}

void EnableSaving(bool enableSaving) {
    bool currentState = g_EnableSaving.load(std::memory_order_acquire);

    if (currentState != enableSaving) {
        if (!enableSaving)
			LOG(LogLevel::Standard, "Saving is disabled either due to a core management save load or a hard reset. Saving will resume once the player exits these states.");
        else
            LOG(LogLevel::Standard, "Saving is enabled.");

        g_EnableSaving.store(enableSaving, std::memory_order_release);
    }
}

void TryLoadSaveState() {
	EnableSaving(false);

	std::ifstream saveFile(g_SavePath);
	if (saveFile.is_open()) {
		std::string line;
		PlayerSaveState loadedState;
		while (std::getline(saveFile, line)) {
			if (line.find("LastSleptHours") != std::string::npos) {
				loadedState.LastSleptHours = std::stoi(line.substr(line.find('=') + 1));
			}
			else if (line.find("LastSleptAtNight") != std::string::npos) {
				loadedState.LastSleptAtNight = (line.substr(line.find('=') + 1, 1) == "1");
			}
			else if (line.find("PostMissionDecayHoursRemaining") != std::string::npos) {
				g_State.PostMissionDecayHoursRemaining = std::stof(line.substr(line.find('=') + 1));
			}
		}
		saveFile.close();
		if (loadedState.IsValid()) {
			g_playerTracker.SetPlayerSaveState(loadedState);
			if (g_CurrentLogLevel.load(std::memory_order_acquire) >= static_cast<int>(LogLevel::Verbose))
			    LOG(LogLevel::Verbose, "Loaded player save state: LastSleptHours={}, LastSleptAtNight={}", loadedState.LastSleptHours, loadedState.LastSleptAtNight);
            else
                LOG(LogLevel::Standard, "Loaded player save state");
		}
		else {
			LOG(LogLevel::Standard, "No valid player save state found in the save file.");
		}
	}
	else {
		LOG(LogLevel::Standard, "No save file found. Starting with default state.");
	}
	
    EnableSaving(true);
}



[[nodiscard]] std::thread InitialiseSaveManagerThread() {
    g_RunSaveManagerThread.store(true, std::memory_order_release);
    return std::thread(AsyncSaveManagerWorker);
}

void ShutdownSaveManager() {
    g_RunSaveManagerThread.store(false, std::memory_order_release);

    // Wake up the condition variable loop in case it's waiting/sleeping
    {
        std::lock_guard<std::mutex> lock(g_SaveManagerMutex);
        g_SaveManagerCV.notify_all();
    }
}